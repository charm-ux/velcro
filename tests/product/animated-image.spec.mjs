  // A source that is not an image: sl-error (bubbling, composed, empty detail), not loaded, no frozen frame or control box.
  await page.evaluate(bad => { document.querySelector('#a').src = bad; }, BAD_IMAGE);
  await expect.poll(async () => (await page.evaluate(() => window.events.map(e => e[0]))).filter(t => t === 'sl-error').length).toBe(1);
  expect(await events(page)).toEqual([['sl-error', 'host', true, true, '{}']]);
  expect(await page.evaluate(() => { const el = document.querySelector('#a'); return [el.isLoaded, el.shadowRoot.querySelectorAll('img').length, Boolean(el.shadowRoot.querySelector('[part="control-box"]'))]; })).toEqual([false, 1, false]);
