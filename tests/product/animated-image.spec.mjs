  await page.evaluate(() => { document.querySelector('#a').play = true; });
  await expect.poll(() => page.evaluate(() => window.imageLoads)).toBeGreaterThanOrEqual(1);
  await page.evaluate(() => { document.querySelector('#a').play = false; });
