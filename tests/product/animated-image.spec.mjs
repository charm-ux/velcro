// Mounts an animated image (id a) with the attributes and inner HTML, with listeners attached before it is connected,
// and waits for its first update. `window.events` collects [type, emitter, bubbles, composed, detail] per sl-load, sl-error
// and ready event that reached the host.
async function mount(page, { attrs = `src="${GIF}" alt="Moving block"`, inner = '', wait = true } = {}) {
  await page.evaluate(async ({ attrs, inner, wait }) => {
    window.events = [];
    const holder = document.createElement('div');
    holder.innerHTML = `<sl-animated-image id="a" ${attrs}>${inner}</sl-animated-image>`;
    const el = holder.firstElementChild;
    for (const type of ['sl-load', 'sl-error', 'ready']) {
      // The event's target is retargeted to the host, so the first entry of its path says who emitted it.
      el.addEventListener(type, e => window.events.push([type, e.composedPath()[0] === el ? 'host' : e.composedPath()[0].localName, e.bubbles, e.composed, JSON.stringify(e.detail)]));
    }
    document.body.replaceChildren(el);
    await el.updateComplete;
    if (wait && el.src) {
      while (!el.isLoaded) await new Promise(resolve => setTimeout(resolve, 20));
      await el.updateComplete;
      await Promise.all([...el.shadowRoot.querySelectorAll('sl-icon')].map(i => i.updateComplete));
    }
    // The loads of the animated image itself from here on (a restart of the animation reloads it).
    window.imageLoads = 0;
    el.shadowRoot.querySelector('.animated-image__animated').addEventListener('load', () => { window.imageLoads += 1; });
  }, { attrs, inner, wait });
}
const events = page => page.evaluate(() => window.events.splice(0));
