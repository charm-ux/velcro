// Turns each checked-in examples/**/*.html file into one entry of src/examples.generated.ts, so the
// displayed source and the executed document come from the same file and no bundler `?raw` support is needed.
// Also emits the catalog, the landing-page showcase (showcase/<name>.html, one per catalog entry) and the on-page
// table of contents of every component page (its <h2 id> headings).
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { apiModel, customElements, readJson, velcroManifestPath } from '../../../scripts/api/model.mjs';
import { readCatalog } from '../../../scripts/site/catalog.mjs';
import { showcaseProblems } from './showcase.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const examplesDir = join(root, 'examples');

function* walk(dir, ext) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* walk(path, ext);
    else if (name.endsWith(ext)) yield path;
  }
}

const entriesOf = ext => [...walk(examplesDir, ext)].map(file => {
  const id = relative(examplesDir, file).split(sep).join('/').slice(0, -ext.length);
  return `  ${JSON.stringify(id)}: ${JSON.stringify(readFileSync(file, 'utf8'))},`;
});

// examples/**/*.jsx are React versions of examples: shown as source only (never executed by the docs site); product
// specs bundle and run the same files against the generated React wrappers.
writeFileSync(
  join(root, 'src', 'examples.generated.ts'),
  `// @generated by scripts/generate-examples.mjs from examples/**/*.html and examples/**/*.jsx - do not edit\n` +
    `export const examples = {\n${entriesOf('.html').join('\n')}\n} as const;\n\n` +
    `export const reactExamples = {\n${entriesOf('.jsx').join('\n')}\n} as const;\n`
);

// The component catalog (packages/docs/catalog.jsonl) is read strictly and emitted as typed data for the shell and home page.
const catalog = readCatalog(fileURLToPath(new URL('../../..', import.meta.url)));
writeFileSync(
  join(root, 'src', 'catalog.generated.ts'),
  `// @generated by scripts/generate-examples.mjs from catalog.jsonl - do not edit\nexport const catalog: ReadonlyArray<{ readonly name: string; readonly title: string; readonly tag: string; readonly example: string }> = ${JSON.stringify(catalog, null, 2)};\n`
);

const showcaseDir = join(root, 'showcase');
const showcaseFiles = existsSync(showcaseDir) ? readdirSync(showcaseDir).filter(f => f.endsWith('.html')).sort() : [];
const readShowcase = f => readFileSync(join(showcaseDir, f), 'utf8');
const problems = showcaseProblems(catalog, showcaseFiles, readShowcase);
if (problems.length) {
  for (const p of problems) process.stderr.write(`showcase: ${p}\n`);
  process.exit(1);
}
writeFileSync(
  join(root, 'src', 'showcase.generated.ts'),
  `// @generated by scripts/generate-examples.mjs from showcase/*.html - do not edit\nexport const showcase: Readonly<Record<string, string>> = {\n${catalog
    .map(c => `  ${JSON.stringify(c.name)}: ${JSON.stringify(readShowcase(`${c.name}.html`).trim())},`)
    .join('\n')}\n};\n`
);

// API tables: each catalog component's model from Velcro's committed Custom Elements Manifest (src/api.ts renders it).
const elements = customElements(readJson(velcroManifestPath));
const api = Object.fromEntries(
  catalog.map(c => {
    const decl = elements.get(c.tag);
    if (!decl) {
      process.stderr.write(`api: ${c.tag} is not in ${velcroManifestPath}\n`);
      process.exit(1);
    }
    return [c.tag, apiModel(decl)];
  })
);
writeFileSync(
  join(root, 'src', 'api.generated.ts'),
  `// @generated by scripts/generate-examples.mjs from ${velcroManifestPath} - do not edit\n`
    + `type Row = { readonly name: string; readonly description: string; readonly origin: string };\n`
    + `export type ApiModel = {\n`
    + `  readonly properties: ReadonlyArray<Row & { readonly attribute: string; readonly type: string; readonly default: string; readonly reflects: boolean; readonly readonly: boolean }>;\n`
    + `  readonly methods: ReadonlyArray<Row & { readonly signature: string }>;\n`
    + `  readonly events: ReadonlyArray<Row & { readonly type: string }>;\n`
    + `  readonly slots: ReadonlyArray<Row>;\n`
    + `  readonly parts: ReadonlyArray<Row>;\n`
    + `  readonly cssProperties: ReadonlyArray<Row & { readonly default: string }>;\n`
    + `};\n`
    + `export const api: Readonly<Record<string, ApiModel>> = ${JSON.stringify(api, null, 2)};\n`
);

// On-page table of contents: the <h2 id="..."> headings of each component page, in source order. A page's
// apiReference(...) call stands for the generated API section headings (src/api.ts) at that position.
const apiHeadings = [...readFileSync(join(root, 'src', 'api.ts'), 'utf8').matchAll(/\['([a-z-]+)', '([^']+)'\]/g)]
  .map(m => ({ id: m[1], text: m[2] }));
const toc = Object.fromEntries(
  catalog.map(c => {
    const source = readFileSync(join(root, 'pages', 'components', `${c.name}.ts`), 'utf8');
    const found = [
      ...[...source.matchAll(/<h2 id="([a-z0-9-]+)">([\s\S]*?)<\/h2>/g)].map(m => ({
        index: m.index,
        entries: [{ id: m[1], text: m[2].replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim() }],
      })),
      ...[...source.matchAll(/\bapiReference\(/g)].map(m => ({ index: m.index, entries: apiHeadings })),
    ].sort((a, b) => a.index - b.index);
    return [c.name, found.flatMap(f => f.entries)];
  })
);
writeFileSync(
  join(root, 'src', 'toc.generated.ts'),
  `// @generated by scripts/generate-examples.mjs from pages/components/*.ts - do not edit\nexport const toc: Readonly<Record<string, ReadonlyArray<{ readonly id: string; readonly text: string }>>> = ${JSON.stringify(toc, null, 2)};\n`
);
