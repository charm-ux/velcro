// Turns each checked-in examples/**/*.html file into one entry of src/examples.generated.ts, so the
// displayed source and the executed document come from the same file and no bundler `?raw` support is needed.
// Also emits the catalog, the landing-page showcase (showcase/<name>.html, one per catalog entry) and the on-page
// table of contents of every component page (its <h2 id> headings).
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readCatalog } from '../../../scripts/site/catalog.mjs';
import { showcaseProblems } from './showcase.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const examplesDir = join(root, 'examples');

function* walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* walk(path);
    else if (name.endsWith('.html')) yield path;
  }
}

const entries = [...walk(examplesDir)].map(file => {
  const id = relative(examplesDir, file).split(sep).join('/').replace(/\.html$/, '');
  return `  ${JSON.stringify(id)}: ${JSON.stringify(readFileSync(file, 'utf8'))},`;
});

writeFileSync(
  join(root, 'src', 'examples.generated.ts'),
  `// @generated by scripts/generate-examples.mjs from examples/**/*.html - do not edit\nexport const examples = {\n${entries.join('\n')}\n} as const;\n`
);

// The component catalog (packages/docs/catalog.jsonl) is read strictly and emitted as typed data for the shell and home page.
const catalog = readCatalog(fileURLToPath(new URL('../../..', import.meta.url)));
writeFileSync(
  join(root, 'src', 'catalog.generated.ts'),
  `// @generated by scripts/generate-examples.mjs from catalog.jsonl - do not edit\nexport const catalog: ReadonlyArray<{ readonly name: string; readonly title: string; readonly tag: string; readonly example: string }> = ${JSON.stringify(catalog, null, 2)};\n`
);

const showcaseDir = join(root, 'showcase');
const showcaseFiles = existsSync(showcaseDir) ? readdirSync(showcaseDir).filter(f => f.endsWith('.html')).sort() : [];
const readShowcase = f => readFileSync(join(showcaseDir, f), 'utf8');
const problems = showcaseProblems(catalog, showcaseFiles, readShowcase);
if (problems.length) {
  for (const p of problems) process.stderr.write(`showcase: ${p}\n`);
  process.exit(1);
}
writeFileSync(
  join(root, 'src', 'showcase.generated.ts'),
  `// @generated by scripts/generate-examples.mjs from showcase/*.html - do not edit\nexport const showcase: Readonly<Record<string, string>> = {\n${catalog
    .map(c => `  ${JSON.stringify(c.name)}: ${JSON.stringify(readShowcase(`${c.name}.html`).trim())},`)
    .join('\n')}\n};\n`
);

// On-page table of contents: the <h2 id="..."> headings of each component page, in source order.
const toc = Object.fromEntries(
  catalog.map(c => {
    const source = readFileSync(join(root, 'pages', 'components', `${c.name}.ts`), 'utf8');
    const entries = [...source.matchAll(/<h2 id="([a-z0-9-]+)">([\s\S]*?)<\/h2>/g)].map(m => ({
      id: m[1],
      text: m[2].replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim(),
    }));
    return [c.name, entries];
  })
);
writeFileSync(
  join(root, 'src', 'toc.generated.ts'),
  `// @generated by scripts/generate-examples.mjs from pages/components/*.ts - do not edit\nexport const toc: Readonly<Record<string, ReadonlyArray<{ readonly id: string; readonly text: string }>>> = ${JSON.stringify(toc, null, 2)};\n`
);
